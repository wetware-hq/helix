// Bundle the repository's canonical files into the Worker: DISCLAIMER, the genome seed
// and the fixed (non-page) part of ooc/helix.og. Run after editing any of them.
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("../../", import.meta.url);
const read = (p) => readFileSync(new URL(p, root), "utf8");

const disclaimer = read("DISCLAIMER").trim();
const genome = JSON.parse(read("genome.json"));
const og = read("ooc/helix.og");

const blocks = og.split(/\n(?=::)/);
const meta = [];
const schema = [];
const indexPre = [];
const indexPost = [];
const nodesPre = [];
const nodesPost = [];

const indexBlock = og.match(/::index\n([\s\S]*?)\n::end/)[1].split("\n");
let seenPageRow = false;
for (const row of indexBlock) {
  const type = row.split("|")[1]?.trim();
  if (type === "page") {
    seenPageRow = true;
    continue;
  }
  (seenPageRow ? indexPost : indexPre).push(row);
}

for (const line of og.match(/::meta\n([\s\S]*?)\n::end/)[1].split("\n")) {
  if (!line.startsWith("checksum:") && !line.startsWith("updated:")) meta.push(line);
}
schema.push(og.match(/::schema\n([\s\S]*?)\n::end/)[1]);

let seenPageNode = false;
for (const m of og.matchAll(/::node \[id=([^\s\]]+)([^\]]*)\]\n([\s\S]*?)\n::end\n::end/g)) {
  const [block, id, , body] = [m[0], m[1], m[2], m[3]];
  const isPage = /type=page/.test(m[2]);
  if (isPage) {
    seenPageNode = true;
    continue;
  }
  void body;
  void id;
  (seenPageNode ? nodesPost : nodesPre).push(block);
}

const out = {
  disclaimer,
  genome,
  og: { meta, schema, indexPre, indexPost, nodesPre, nodesPost },
};

writeFileSync(
  new URL("../src/generated/static.ts", import.meta.url),
  "// Generated by scripts/gen-static.mjs from DISCLAIMER, genome.json and ooc/helix.og.\n" +
    "// Do not edit by hand.\n" +
    "import type { Genome } from \"../lib/model\";\n\n" +
    `export const DISCLAIMER = ${JSON.stringify(out.disclaimer)};\n\n` +
    `export const GENOME_SEED = ${JSON.stringify(out.genome, null, 2)} as unknown as Genome;\n\n` +
    `export const OG = ${JSON.stringify(out.og, null, 2)} as const;\n`,
);
console.log("wrote src/generated/static.ts");
